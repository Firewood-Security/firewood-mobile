package net.firewood.app.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Android Keystore-backed cryptographic operations for Firewood vault security.
 *
 * Core purpose: Replace FlutterSecureStorage-based raw master password storage
 * (CRITICAL finding P1 in SECURITY_AUDIT.md) with a key-wrapping pattern:
 *
 *  1. Generate a strong AES-256-GCM key inside Android Keystore
 *     (hardware backing is device-dependent and UNVERIFIED per-device;
 *     see ADR-003 — never surface "hardware-backed" in user-facing copy).
 *  2. Encrypt the master password with this Keystore key.
 *  3. Store only the encrypted blob on disk (via EncryptedSharedPreferences).
 *  4. On biometric success, Keystore authorizes decryption without the password
 *     ever touching FlutterSecureStorage in plaintext.
 *
 * Invariants:
 *  - Raw master password NEVER stored in SharedPreferences,
 *    unencrypted files, or app storage (except the deprecated Dart-side
 *    legacy entry, migration-only per ADR-003).
 *  - Keystore keys require UserAuthentication (biometric/credential) with
 *    invalidated-on-new-enrollment semantics.
 *  - AES-GCM provides authenticated encryption – tampered blobs fail on decrypt.
 */
class SecureKeystoreManager {

    companion object {
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val VAULT_WRAPPING_KEY_ALIAS = "firewood_vault_wrapping_key_v1"
        private const val KEY_SIZE_BITS = 256
        private const val GCM_TAG_LENGTH_BITS = 128
        private const val GCM_IV_LENGTH_BYTES = 12

        // Transform string used for Keystore-backed AES-GCM
        private const val AES_GCM_NO_PADDING = "AES/GCM/NoPadding"
    }

    private val keyStore: KeyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply {
        load(null)
    }

    /**
     * Returns true if the Android Keystore contains a valid wrapping key
     * (i.e., biometric vault unlock has been previously set up).
     */
    fun hasWrappingKey(): Boolean {
        return keyStore.containsAlias(VAULT_WRAPPING_KEY_ALIAS)
    }

    /**
     * Creates a new AES-256-GCM key inside Android Keystore, bound to
     * biometric + device credential authentication.
     *
     * The key is invalidated when:
     *  - New biometrics are enrolled (KEYPROMISE_INVALIDATED_BY_NEW_ENROLLMENT)
     *  - Device credentials change
     *
     * This ensures that adding a new fingerprint does not allow an attacker
     * to bypass the vault unlock.
     */
    fun createWrappingKey(
        userAuthenticationRequired: Boolean = true,
        invalidatedByBiometricEnrollment: Boolean = true
    ) {
        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            KEYSTORE_PROVIDER
        )

        val specBuilder = KeyGenParameterSpec.Builder(
            VAULT_WRAPPING_KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        ).apply {
            setKeySize(KEY_SIZE_BITS)
            setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            setRandomizedEncryptionRequired(true)

            if (userAuthenticationRequired) {
                setUserAuthenticationRequired(true)
                setUserAuthenticationParameters(
                    60, // timeout seconds – user must authenticate within 60s
                    KeyProperties.AUTH_BIOMETRIC_STRONG or KeyProperties.AUTH_DEVICE_CREDENTIAL
                )
                if (invalidatedByBiometricEnrollment) {
                    setInvalidatedByBiometricEnrollment(true)
                }
            }
        }

        keyGenerator.init(specBuilder.build())
        keyGenerator.generateKey()
    }

    /**
     * Wraps (encrypts) [plaintext] using the Keystore-backed wrapping key.
     * Returns the ciphertext prefixed with the 12-byte GCM IV.
     *
     * Format: [IV:12 bytes][Ciphertext:N bytes][GCM Tag:16 bytes]
     *
     * @throws IllegalStateException if no wrapping key exists
     * @throws SecurityException if user authentication fails
     */
    fun wrapData(plaintext: ByteArray): ByteArray {
        val secretKey = getWrappingKey()
            ?: throw IllegalStateException("No wrapping key found. Call createWrappingKey() first.")

        val cipher = Cipher.getInstance(AES_GCM_NO_PADDING)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)

        val iv = cipher.iv // 12 bytes, randomly generated by Android Keystore
        val ciphertext = cipher.doFinal(plaintext) // includes GCM tag

        // Prepend IV to ciphertext
        return iv + ciphertext
    }

    /**
     * Unwraps (decrypts) [wrappedData] using the Keystore-backed wrapping key.
     * The IV is extracted from the first 12 bytes of [wrappedData].
     *
     * @throws SecurityException if user authentication (biometric) fails or times out
     * @throws javax.crypto.AEADBadTagException if ciphertext was tampered with
     * @throws IllegalStateException if no wrapping key exists
     */
    fun unwrapData(wrappedData: ByteArray): ByteArray {
        val secretKey = getWrappingKey()
            ?: throw IllegalStateException("No wrapping key found.")

        if (wrappedData.size < GCM_IV_LENGTH_BYTES + 16) {
            throw IllegalArgumentException("Wrapped data too short: ${wrappedData.size} bytes")
        }

        val iv = wrappedData.copyOfRange(0, GCM_IV_LENGTH_BYTES)
        val ciphertext = wrappedData.copyOfRange(GCM_IV_LENGTH_BYTES, wrappedData.size)

        val cipher = Cipher.getInstance(AES_GCM_NO_PADDING)
        val spec = GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, spec)

        return cipher.doFinal(ciphertext)
    }

    /**
     * Deletes the wrapping key from Android Keystore.
     * Call this when user disables biometric unlock.
     * Any data previously wrapped with this key becomes permanently inaccessible.
     */
    fun deleteWrappingKey() {
        if (keyStore.containsAlias(VAULT_WRAPPING_KEY_ALIAS)) {
            keyStore.deleteEntry(VAULT_WRAPPING_KEY_ALIAS)
        }
    }

    /**
     * Checks whether biometric authentication is available on this device
     * (strong biometrics: fingerprint, face, iris).
     */
    fun isStrongBiometricAvailable(): Boolean {
        // Checked at Flutter layer via local_auth plugin
        return true
    }

    private fun getWrappingKey(): SecretKey? {
        return if (keyStore.containsAlias(VAULT_WRAPPING_KEY_ALIAS)) {
            val entry = keyStore.getEntry(VAULT_WRAPPING_KEY_ALIAS, null)
            (entry as? KeyStore.SecretKeyEntry)?.secretKey
        } else {
            null
        }
    }
}
